// gen draws Tic-tac-toe's client files: an X in every red and an O in every
// cyan that Concord's built-in themes use (so pieces match whatever theme a
// viewer picked), and its sounds. It also writes game/pieces_gen.go, the
// list of colors drawn. Run from the repo root: go run tools/gen.go
